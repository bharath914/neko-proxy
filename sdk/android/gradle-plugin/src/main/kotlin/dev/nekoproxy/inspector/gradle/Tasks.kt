/** Writes `assets/inspector.properties` from the extension, so the SDK can read a manual desktop address. */
abstract class GenerateInspectorConfig : DefaultTask() {
    @get:Input @get:Optional abstract val host: Property<String>
    @get:Input @get:Optional abstract val port: Property<Int>
    @get:Input @get:Optional abstract val desktopName: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun write() {
        val dir = outputDir.get().asFile.also { it.mkdirs() }
        val p = java.util.Properties()
        host.orNull?.let { p.setProperty("host", it) }
        port.orNull?.let { p.setProperty("port", it.toString()) }
        desktopName.orNull?.let { p.setProperty("desktopName", it) }
        java.io.File(dir, "inspector.properties").outputStream().use { p.store(it, "Generated by the Neko Inspector Gradle plugin") }
    }
}

/** Prints what the plugin did and what to fix. Run `./gradlew inspectorDoctor`. */
@DisableCachingByDefault(because = "prints to the console")
abstract class InspectorDoctor : DefaultTask() {
    @get:Input abstract val applied: Property<Boolean>
    @get:Input abstract val report: MapProperty<String, String>
    @get:Input abstract val enabledBuildTypes: org.gradle.api.provider.SetProperty<String>

    /** The merged manifest of one enabled variant, to check INTERNET. */
    @get:InputFile @get:Optional @get:PathSensitive(PathSensitivity.NONE) abstract val manifest: RegularFileProperty

    @TaskAction
    fun run() {
        val out = StringBuilder("Neko Inspector doctor\n")
        if (!applied.get()) {
            out.append("  The Android plugin is not applied to this project. Apply `com.android.application` before `dev.nekoproxy.inspector`.\n")
            logger.lifecycle(out.toString()); return
        }
        out.append("  Plugin: applied. Real SDK for build types: ${enabledBuildTypes.get().sorted().joinToString()}\n")
        for ((variant, what) in report.get().toSortedMap()) out.append("  Variant $variant: $what\n")
        val m = manifest.orNull?.asFile
        if (m != null && m.exists()) {
            val has = m.readText().contains("android.permission.INTERNET")
            out.append(if (has) "  INTERNET permission: declared\n" else "  INTERNET permission: MISSING. Add <uses-permission android:name=\"android.permission.INTERNET\"/> to the manifest.\n")
        }
        if (enabledBuildTypes.get().isEmpty()) out.append("  No build type is enabled: nothing will be captured. Set inspector { enabledBuildTypes = setOf(\"debug\") }.\n")
        out.append("  To verify a release build: ./gradlew verifyNoInspectorInRelease (fails if real SDK classes are on its classpath).\n")
        logger.lifecycle(out.toString())
    }
}

/** Fails if a build that should carry only the no-op contains real SDK classes or strings. */
@DisableCachingByDefault(because = "verification")
abstract class VerifyNoInspector : DefaultTask() {
    @get:org.gradle.api.tasks.InputDirectory
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val apkDir: DirectoryProperty

    @get:Input abstract val variantName: Property<String>

    @TaskAction
    fun verify() {
        val markers = listOf("Ldev/nekoproxy/inspector/internal/", "_nekoinspect", "inspector-pairing", "InspectorOkHttp;.install")
        val apks = apkDir.get().asFile.walkTopDown().filter { it.extension == "apk" }.toList()
        if (apks.isEmpty()) throw org.gradle.api.GradleException("No APK found for ${variantName.get()}; run assemble first.")
        val bad = mutableListOf<String>()
        for (apk in apks) java.util.zip.ZipFile(apk).use { z ->
            for (e in z.entries()) {
                if (!e.name.endsWith(".dex")) {
                    if (e.name == "assets/inspector.properties") bad += "${apk.name}: ${e.name}"
                    continue
                }
                val text = String(z.getInputStream(e).readBytes(), Charsets.ISO_8859_1)
                for (m in markers) if (m in text) bad += "${apk.name}: ${e.name} contains \"$m\""
            }
        }
        if (bad.isNotEmpty()) throw org.gradle.api.GradleException(
            "The ${variantName.get()} build contains real Inspector code:\n  " + bad.joinToString("\n  ") +
                "\nIt should only have the no-op. Check inspector { enabledBuildTypes } and that nothing adds inspector-android to this variant.",
        )
        logger.lifecycle("${variantName.get()}: no Inspector capture code found in ${apks.size} APK(s).")
    }
}
